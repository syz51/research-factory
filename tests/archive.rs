//! End-to-end: `lab archive` indexes, seals, checks, finds and numbers records
//! in a small synthetic archive.

use std::path::Path;
use std::process::{Command, Output};

fn lab(dir: &Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_lab"))
        .args(args)
        .current_dir(dir)
        .output()
        .expect("run lab")
}

fn stdout(o: &Output) -> String {
    String::from_utf8_lossy(&o.stdout).into_owned()
}

fn stderr(o: &Output) -> String {
    String::from_utf8_lossy(&o.stderr).into_owned()
}

fn write(dir: &Path, rel: &str, text: &str) {
    let path = dir.join(rel);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(path, text).unwrap();
}

fn read(dir: &Path, rel: &str) -> String {
    std::fs::read_to_string(dir.join(rel)).unwrap()
}

fn append(dir: &Path, rel: &str, text: &str) {
    write(dir, rel, &(read(dir, rel) + text));
}

const CONFIG: &str = r#"[project]
name = "demo"

[lab.archive]
start = "docs/START.md"
seal_manifest = "docs/.seal.json"
sealed = ["docs/history/[0-9]*.md", "docs/log/*.md"]
links = ["docs/**/*.md"]
links_exclude = ["docs/inputs/**"]
current_pages = ["docs/START.md"]

[[lab.archive.index]]
name = "decisions"
output = "docs/decisions/INDEX.md"
title = "Decisions"
include = ["docs/decisions/D*.md"]
id_from = '^(D\d+)-'
group_by = "status"
require = ["id", "title", "status"]

[[lab.archive.index]]
name = "history"
output = "docs/history/INDEX.md"
title = "History reports"
intro = "Newest first."
include = ["docs/history/[0-9]*.md"]
id_from = '^(\d+[a-z]?)-'
id_prefix = "H"
trim_leading_zeros = true
sort = "id-desc"
require = ["id", "title", "date"]

[[lab.archive.budget]]
path = "docs/START.md"
max_bytes = 400
severity = "error"
"#;

/// A small archive: two decisions (one superseding the other), two history
/// reports, a monthly log and a start page.
fn archive(d: &Path) {
    write(d, "research.toml", CONFIG);
    write(
        d,
        "docs/START.md",
        "# Start\n\nCurrent: [D002](decisions/D002-use-bm25.md). Earlier: [D001](decisions/D001-use-tfidf.md).\n",
    );
    write(
        d,
        "docs/decisions/D001-use-tfidf.md",
        "---\nstatus: superseded\nsuperseded_by: D002\n---\n# Use TF-IDF\n",
    );
    write(
        d,
        "docs/decisions/D002-use-bm25.md",
        "---\ntitle: Use BM25\nstatus: accepted\nsupersedes: [D001]\naliases: [lexical baseline]\nsummary: BM25 is the first-stage retriever\n---\n# D002\n\n## Why\n\nIt is strong.\n",
    );
    write(
        d,
        "docs/history/01-2026-10-02-start.md",
        "# Start of the project\n\nSee [the decision](../decisions/D002-use-bm25.md#why).\n",
    );
    write(
        d,
        "docs/history/02-2026-10-03-pilot.md",
        "# Pilot run\n\nRan the pilot.\n",
    );
    write(
        d,
        "docs/log/2026-10.md",
        "# October 2026\n\n- 2026-10-02: began.\n",
    );
    write(d, "docs/inputs/copied.md", "[gone](nowhere.md)\n");
}

fn check(d: &Path) -> (Option<i32>, String) {
    let out = lab(d, &["archive", "check"]);
    assert!(stderr(&out).is_empty(), "{}", stderr(&out));
    (out.status.code(), stdout(&out))
}

fn rules(text: &str) -> Vec<String> {
    text.lines()
        .filter(|l| l.starts_with("error ") || l.starts_with("warn "))
        .map(|l| l.split(' ').take(3).collect::<Vec<_>>().join(" "))
        .collect()
}

#[test]
fn update_generates_indexes_and_seals_then_check_passes() {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    archive(d);

    let (code, text) = check(d);
    assert_eq!(code, Some(1), "{text}");
    assert_eq!(
        rules(&text),
        [
            "warn superseded-link docs/START.md:3",
            "error index-missing docs/decisions/INDEX.md",
            "warn unsealed docs/history/01-2026-10-02-start.md",
            "warn unsealed docs/history/02-2026-10-03-pilot.md",
            "error index-missing docs/history/INDEX.md",
            "warn unsealed docs/log/2026-10.md",
        ],
        "{text}"
    );

    let update = lab(d, &["archive", "update"]);
    assert_eq!(update.status.code(), Some(0), "{}", stdout(&update));
    let out = stdout(&update);
    assert!(
        out.contains("wrote docs/decisions/INDEX.md\nwrote docs/history/INDEX.md\n"),
        "{out}"
    );
    assert!(out.contains("sealed docs/log/2026-10.md"), "{out}");
    assert!(out.contains("wrote docs/.seal.json"), "{out}");

    assert_eq!(
        read(d, "docs/decisions/INDEX.md"),
        "<!-- Generated by `lab archive update` from front matter. Do not edit by hand. -->\n\
         # Decisions\n\n## Accepted\n\n\
         - [D002](D002-use-bm25.md) — Use BM25. BM25 is the first-stage retriever. Aliases: lexical baseline.\n\n\
         ## Superseded\n\n- [D001](D001-use-tfidf.md) — Use TF-IDF.\n"
    );
    assert_eq!(
        read(d, "docs/history/INDEX.md"),
        "<!-- Generated by `lab archive update` from front matter. Do not edit by hand. -->\n\
         # History reports\n\nNewest first.\n\n\
         - [H2](02-2026-10-03-pilot.md) · 2026-10-03 — Pilot run.\n\
         - [H1](01-2026-10-02-start.md) · 2026-10-02 — Start of the project.\n"
    );
    let again = stdout(&lab(d, &["archive", "update"]));
    assert!(
        again.contains("unchanged docs/decisions/INDEX.md\nunchanged docs/history/INDEX.md\n"),
        "{again}"
    );
    assert!(!again.contains("wrote"), "a rerun writes nothing: {again}");

    // The link to the superseded decision says so; the check passes.
    write(
        d,
        "docs/START.md",
        "# Start\n\nCurrent: [D002](decisions/D002-use-bm25.md). Superseded: [D001](decisions/D001-use-tfidf.md).\n",
    );
    let (code, text) = check(d);
    assert_eq!(code, Some(0), "{text}");
    assert!(
        text.ends_with("0 error(s), 0 warning(s) in the archive.\n"),
        "{text}"
    );

    // Editing a record's front matter makes its index stale.
    let d2 = read(d, "docs/decisions/D002-use-bm25.md").replace("Use BM25", "Use BM25 first");
    write(d, "docs/decisions/D002-use-bm25.md", &d2);
    let (code, text) = check(d);
    assert_eq!(code, Some(1));
    assert_eq!(
        rules(&text),
        ["error index-stale docs/decisions/INDEX.md"],
        "{text}"
    );
    assert!(text.contains("run `lab archive update`"), "{text}");
    assert!(lab(d, &["archive", "index"]).status.success());
    assert_eq!(check(d).0, Some(0));

    let brief = stdout(&lab(d, &["brief"]));
    assert!(brief.contains("## Archive"), "{brief}");
    assert!(
        brief.contains("- Read docs/START.md first (0.1 KB)."),
        "{brief}"
    );
    assert!(
        brief.contains("`lab archive find <words>`, or the indexes docs/decisions/INDEX.md, docs/history/INDEX.md."),
        "{brief}"
    );
}

#[test]
fn seals_allow_appends_and_front_matter_but_catch_edits() {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    archive(d);
    let start = read(d, "docs/START.md").replace("Earlier:", "Superseded:");
    write(d, "docs/START.md", &start);
    assert!(lab(d, &["archive", "update"]).status.success());

    append(d, "docs/log/2026-10.md", "- 2026-10-03: piloted.\n");
    let seal = lab(d, &["archive", "seal"]);
    assert_eq!(seal.status.code(), Some(0), "{}", stdout(&seal));
    assert!(stdout(&seal).contains("appended docs/log/2026-10.md"));

    // A status change in front matter leaves the sealed body alone.
    let h1 = read(d, "docs/history/01-2026-10-02-start.md");
    write(
        d,
        "docs/history/01-2026-10-02-start.md",
        &format!("---\nstatus: historical\n---\n{h1}"),
    );
    assert!(lab(d, &["archive", "update"]).status.success());
    assert_eq!(check(d).0, Some(0));

    let log = read(d, "docs/log/2026-10.md").replace("began", "started");
    write(d, "docs/log/2026-10.md", &log);
    let (code, text) = check(d);
    assert_eq!(code, Some(1));
    assert_eq!(
        rules(&text),
        ["error sealed-edited docs/log/2026-10.md"],
        "{text}"
    );
    let seal = lab(d, &["archive", "seal"]);
    assert_eq!(seal.status.code(), Some(1));
    assert!(
        stdout(&seal).contains("edited docs/log/2026-10.md"),
        "{}",
        stdout(&seal)
    );
    let update = lab(d, &["archive", "update"]);
    assert_eq!(update.status.code(), Some(1), "update reports the edit too");

    let refused = lab(d, &["archive", "seal", "--accept", "docs/log/2026-10.md"]);
    assert_eq!(refused.status.code(), Some(2), "--accept needs --note");
    let accept = lab(
        d,
        &[
            "archive",
            "seal",
            "--accept",
            "docs/log/2026-10.md",
            "--note",
            "fixed a wrong verb",
        ],
    );
    assert!(accept.status.success(), "{}", stderr(&accept));
    let manifest: serde_json::Value = serde_json::from_str(&read(d, "docs/.seal.json")).unwrap();
    assert_eq!(manifest["schema"], "rf.archive-seal/1");
    let history = manifest["history"].as_array().unwrap();
    assert_eq!(history.len(), 1);
    assert_eq!(history[0]["path"], "docs/log/2026-10.md");
    assert_eq!(history[0]["note"], "fixed a wrong verb");
    assert_ne!(history[0]["old_sha256"], history[0]["new_sha256"]);
    assert_eq!(check(d).0, Some(0));

    std::fs::remove_file(d.join("docs/log/2026-10.md")).unwrap();
    let (code, text) = check(d);
    assert_eq!(code, Some(1));
    assert_eq!(
        rules(&text),
        ["error sealed-missing docs/log/2026-10.md"],
        "{text}"
    );
    assert_eq!(lab(d, &["archive", "seal"]).status.code(), Some(1));
    let manifest = read(d, "docs/.seal.json");
    assert!(
        manifest.contains("docs/log/2026-10.md"),
        "a missing file keeps its seal"
    );
}

#[test]
fn check_finds_record_link_and_size_problems() {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    archive(d);
    assert!(lab(d, &["archive", "update"]).status.success());
    append(
        d,
        "docs/history/02-2026-10-03-pilot.md",
        "\nSee [missing](../nope.md), [bad anchor](../decisions/D002-use-bm25.md#how), \
         [self](#pilot-run), [self bad](#nowhere), [dir](../decisions/), \
         [code](../../src/x.py#L10) and `[not a link](x.md)`.\n\n```\n[fenced](x.md)\n```\n",
    );
    write(d, "src/x.py", "");
    // Two reports numbered 02, and a third decision with problems.
    write(d, "docs/history/02-2026-10-04-again.md", "# Again\n");
    write(
        d,
        "docs/decisions/D003-rerank.md",
        "---\nstatus: proposed\nsupersedes: D002\nsuperseded_by: D009\ndecisions: [D001]\n---\n# Rerank\n",
    );
    write(d, "docs/decisions/D004-x.md", "# No status here\n");
    append(d, "docs/START.md", &"padding ".repeat(50));

    let out = lab(d, &["archive", "check"]);
    let text = stdout(&out);
    assert_eq!(out.status.code(), Some(1), "{text}");
    assert_eq!(
        rules(&text),
        [
            "error size-budget docs/START.md",
            "warn superseded-link docs/START.md:3",
            "warn superseded-but-active docs/decisions/D003-rerank.md",
            "warn supersession-mismatch docs/decisions/D003-rerank.md",
            "error unknown-id docs/decisions/D003-rerank.md",
            "error missing-field docs/decisions/D004-x.md",
            "error index-stale docs/decisions/INDEX.md",
            "error duplicate-id H2",
            "error broken-anchor docs/history/02-2026-10-03-pilot.md:5",
            "error broken-anchor docs/history/02-2026-10-03-pilot.md:5",
            "error broken-link docs/history/02-2026-10-03-pilot.md:5",
            "warn unsealed docs/history/02-2026-10-04-again.md",
            "error index-stale docs/history/INDEX.md",
        ],
        "{text}"
    );
    assert!(text.contains("2 records have id H2: docs/history/02-2026-10-03-pilot.md, docs/history/02-2026-10-04-again.md"), "{text}");
    assert!(
        text.contains("links to `../nope.md`, which does not exist"),
        "{text}"
    );
    assert!(
        text.contains(
            "`../decisions/D002-use-bm25.md#how`, but the target has no heading or anchor `#how`"
        ),
        "{text}"
    );
    assert!(text.contains("`#nowhere`"), "{text}");
    assert!(text.contains("`superseded_by` names D009"), "{text}");
    assert!(
        text.contains("supersedes D002, but D002's `superseded_by` does not list D003"),
        "{text}"
    );
    assert!(
        text.contains("has no `status`, which index `decisions` requires"),
        "{text}"
    );

    let jsonl = lab(d, &["archive", "check", "--format", "jsonl"]);
    assert_eq!(jsonl.status.code(), Some(1));
    let findings: Vec<serde_json::Value> = stdout(&jsonl)
        .lines()
        .map(|l| serde_json::from_str(l).unwrap())
        .collect();
    assert_eq!(findings.len(), 13);
    assert!(
        findings
            .iter()
            .all(|f| f["schema"] == "rf.finding/1" && f["tool"] == "lab")
    );
    let budget = findings
        .iter()
        .find(|f| f["rule"] == "size-budget")
        .unwrap();
    assert_eq!(budget["data"]["max_bytes"], 400);
    let dup = findings
        .iter()
        .find(|f| f["rule"] == "duplicate-id")
        .unwrap();
    assert_eq!(dup["evidence"].as_array().unwrap().len(), 2);

    // Invalid front matter: nothing is written and the record is reported.
    write(
        d,
        "docs/decisions/D005-bad.md",
        "---\nstatus: maybe\n---\n# Bad\n",
    );
    let index = lab(d, &["archive", "index"]);
    assert_eq!(index.status.code(), Some(1));
    assert!(
        stdout(&index).contains("error front-matter-invalid docs/decisions/D005-bad.md:1 — `status` `maybe` is not one of"),
        "{}",
        stdout(&index)
    );
    assert!(!stdout(&index).contains("wrote"));
}

#[test]
fn find_and_next() {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    archive(d);
    write(
        d,
        "docs/decisions/D010-d.md",
        "---\ntitle: Mentions D002\nstatus: draft\n---\n",
    );

    let find = lab(d, &["archive", "find", "d002"]);
    assert!(find.status.success(), "{}", stderr(&find));
    assert_eq!(
        stdout(&find),
        "D002\t-\taccepted\tdocs/decisions/D002-use-bm25.md\tUse BM25\n\
         D010\t-\tdraft\tdocs/decisions/D010-d.md\tMentions D002\n"
    );
    let alias = stdout(&lab(d, &["archive", "find", "lexical", "BASELINE"]));
    assert!(alias.starts_with("D002\t"), "{alias}");
    let h = stdout(&lab(d, &["archive", "find", "pilot"]));
    assert_eq!(
        h,
        "H2\t2026-10-03\t-\tdocs/history/02-2026-10-03-pilot.md\tPilot run\n"
    );
    let limited = lab(d, &["archive", "find", "docs", "--limit", "1"]);
    assert_eq!(stdout(&limited).lines().count(), 1);
    assert!(
        stderr(&limited).contains("more match(es)"),
        "{}",
        stderr(&limited)
    );
    let none = lab(d, &["archive", "find", "zebra"]);
    assert_eq!(none.status.code(), Some(1));
    assert!(
        stderr(&none).contains("decisions (docs/decisions/INDEX.md)"),
        "{}",
        stderr(&none)
    );

    assert_eq!(stdout(&lab(d, &["archive", "next", "H"])), "H3\n");
    assert_eq!(stdout(&lab(d, &["archive", "next", "D"])), "D011\n");
    let q = lab(d, &["archive", "next", "Q"]);
    assert_eq!(q.status.code(), Some(1));
    assert!(stderr(&q).contains("--width"), "{}", stderr(&q));
    assert_eq!(
        stdout(&lab(d, &["archive", "next", "Q", "--width", "3"])),
        "Q001\n"
    );
}

#[test]
fn lab_check_stores_archive_findings_and_keeps_their_fingerprints() {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    archive(d);
    let cfg = read(d, "research.toml")
        + &format!(
            "\n[[lab.checks]]\nname = \"archive\"\nrun = [\"{}\", \"archive\", \"check\", \"--format\", \"jsonl\"]\n",
            env!("CARGO_BIN_EXE_lab")
        );
    write(d, "research.toml", &cfg);
    assert!(lab(d, &["archive", "update"]).status.success());
    append(
        d,
        "docs/history/02-2026-10-03-pilot.md",
        "\n[broken](gone.md)\n",
    );

    let first = lab(d, &["check", "--verbose"]);
    assert_eq!(first.status.code(), Some(1), "{}", stdout(&first));
    let out = stdout(&first);
    assert!(
        out.contains("error lab:broken-link docs/history/02-2026-10-03-pilot.md:5"),
        "{out}"
    );
    assert!(
        lab(d, &["baseline", "set", "--note", "existing broken link"])
            .status
            .success()
    );

    // Lines added above the link, an append to the log and a newer index do
    // not make the accepted finding new.
    let pilot = read(d, "docs/history/02-2026-10-03-pilot.md");
    write(
        d,
        "docs/history/02-2026-10-03-pilot.md",
        &pilot.replace("Ran the pilot.\n", "Ran the pilot.\n\nMore detail.\n"),
    );
    append(d, "docs/log/2026-10.md", "- 2026-10-04: more.\n");
    write(d, "docs/history/03-2026-10-05-next.md", "# Next\n");
    assert!(lab(d, &["archive", "update"]).status.success());
    let second = lab(d, &["check", "--new-only"]);
    assert_eq!(second.status.code(), Some(0), "{}", stdout(&second));

    write(
        d,
        "docs/history/03-2026-10-05-next.md",
        "# Next\n\n[x](also-gone.md)\n",
    );
    let third = lab(d, &["check", "--new-only"]);
    assert_eq!(third.status.code(), Some(1), "{}", stdout(&third));
    assert!(
        stdout(&third).contains("1 error(s) not in the baseline"),
        "{}",
        stdout(&third)
    );
}

#[test]
fn the_init_template_example_is_valid_once_uncommented() {
    let dir = tempfile::tempdir().unwrap();
    let d = dir.path();
    assert!(lab(d, &["init", "--name", "demo"]).status.success());
    let cfg = read(d, "research.toml");
    let at = cfg.find("# [[lab.checks]]\n# name = \"archive\"").unwrap();
    let example: String = cfg[at..]
        .lines()
        .map(|l| l.strip_prefix("# ").or(l.strip_prefix('#')).unwrap_or(l))
        .collect::<Vec<_>>()
        .join("\n");
    write(d, "research.toml", &format!("{}{example}\n", &cfg[..at]));
    let out = lab(d, &["archive", "update"]);
    assert!(out.status.success(), "{}{}", stdout(&out), stderr(&out));
    assert!(read(d, "docs/research/history/INDEX.md").ends_with("No records yet.\n"));
}

